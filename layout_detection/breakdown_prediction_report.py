#!/usr/bin/env python3
"""
Break down TP and FN predictions by UTR parent category and sequence.

Parses a prediction report (*.txt) generated by predict_and_analyze.py,
matches each TP/FN upstream context to its most likely parent sequence from
KOZAK_SEQUENCES, UTR5_REAL_SEQUENCES, and IRES_SEQUENCES (from utils/sequences.py),
allowing minor mutations via Hamming distance.

Outputs a TSV next to the input report with suffix _breakdown.tsv containing:
  category, parent_index, parent_sequence, parent_len, match_len, mismatch_rate,
  tp_count, fn_count, tp_mutated, fn_mutated

Usage:
  python layout_detection/breakdown_prediction_report.py \
    --report-file layout_detection/utr_start_test_run_*/prediction_..._.txt \
    [--mismatch-threshold 0.15]
"""

import sys
from pathlib import Path
import argparse
import re
from typing import List, Tuple, Dict, Optional

# Add project root to path
project_root = Path(__file__).parent.parent
sys.path.append(str(project_root))

from utils.sequences import KOZAK_SEQUENCES, UTR5_REAL_SEQUENCES, IRES_SEQUENCES


def parse_report_for_tp_fn(report_path: Path) -> List[Dict]:
    """Extract TP and FN entries with upstream context from the report file.

    Returns a list of dicts with keys: sequence_id, position, classification, upstream_60, codon, downstream_20.
    Robust streaming parser that scans the entire file and collects entries under
    'TRUE POSITIVES:' and 'FALSE NEGATIVES (Missed STARTs):' sections.
    """
    lines = report_path.read_text().splitlines()
    entries: List[Dict] = []
    current_class: Optional[str] = None
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        # Detect section switches
        if line == 'TRUE POSITIVES:':
            current_class = 'TP'
            i += 1
            # skip underline if present
            if i < len(lines) and set(lines[i].strip()) == {'-'}:
                i += 1
            continue
        if line.startswith('FALSE NEGATIVES'):
            current_class = 'FN'
            i += 1
            if i < len(lines) and set(lines[i].strip()) == {'-'}:
                i += 1
            continue
        if line.startswith('FALSE POSITIVES'):
            current_class = None  # ignore FP for this analysis
            i += 1
            if i < len(lines) and set(lines[i].strip()) == {'-'}:
                i += 1
            continue

        # Collect entries only when in TP or FN section
        if current_class in ('TP', 'FN') and line.startswith('>sequence_'):
            header = lines[i].strip()
            seq_id_pos = header[1:]
            seq_id, at_pos = seq_id_pos.split('@') if '@' in seq_id_pos else (seq_id_pos, 'NA')
            if i + 1 < len(lines):
                context = lines[i + 1].rstrip('\n')
            else:
                break
            if i + 2 < len(lines):
                marker = lines[i + 2].rstrip('\n')
            else:
                break
            caret_idx = marker.find('^')
            if caret_idx == -1:
                i += 1
                continue
            upstream_60 = context[:caret_idx]
            codon = context[caret_idx:caret_idx + 3] if caret_idx + 3 <= len(context) else ''
            downstream_20 = context[caret_idx + 3:caret_idx + 23] if caret_idx + 3 <= len(context) else ''
            entries.append({
                'sequence_id': seq_id,
                'position': at_pos,
                'classification': current_class,
                'upstream_60': upstream_60,
                'codon': codon,
                'downstream_20': downstream_20,
            })
            i += 3
            continue
        i += 1
    return entries


def build_parent_catalog() -> List[Dict]:
    """Build a catalog of parent sequences with category and index.

    For matching against upstream_60, we use the parent's upstream tail:
    - If parent endswith 'ATG', use parent[:-3] as the upstream region
    - Otherwise, use the full parent sequence as upstream region
    """
    catalog: List[Dict] = []
    for cat, seqs in (
        ('KOZAK', KOZAK_SEQUENCES),
        ('UTR5', UTR5_REAL_SEQUENCES),
        ('IRES', IRES_SEQUENCES),
    ):
        for idx, parent in enumerate(seqs):
            parent_up = parent[:-3] if parent.endswith('ATG') else parent
            catalog.append({
                'category': cat,
                'parent_index': idx,
                'parent_sequence': parent,
                'parent_upstream': parent_up,
                'parent_len': len(parent),
            })
    return catalog


def hamming_distance(a: str, b: str) -> int:
    assert len(a) == len(b)
    return sum(1 for x, y in zip(a, b) if x != y)


def match_upstream_to_parent(upstream_60: str, catalog: List[Dict]) -> Tuple[Optional[Dict], float, int]:
    """Find best parent match for upstream_60 by normalized Hamming distance.

    Compares the parent's upstream tail (up to 60 bases) against the last L bases of upstream_60
    where L = min(len(parent_upstream), len(upstream_60), 60). Returns (best_parent, mismatch_rate, match_len).
    If no parent exists (shouldn't happen), returns (None, 1.0, 0).
    """
    best = None
    best_rate = 1.0
    best_len = 0
    for entry in catalog:
        parent_up = entry['parent_upstream']
        if not parent_up:
            continue
        L = min(len(parent_up), len(upstream_60), 60)
        if L == 0:
            continue
        a = upstream_60[-L:]
        b = parent_up[-L:]
        dist = hamming_distance(a, b)
        rate = dist / L
        if rate < best_rate or (rate == best_rate and L > best_len):
            best = entry
            best_rate = rate
            best_len = L
    return best, best_rate, best_len


def analyze_distribution(entries: List[Dict], mismatch_threshold: float) -> List[Dict]:
    """Aggregate counts by (category, parent_index) with mutation status and summary fields."""
    catalog = build_parent_catalog()
    aggregates: Dict[Tuple[str, int], Dict] = {}

    for e in entries:
        if e['classification'] not in ('TP', 'FN'):
            continue
        best, rate, match_len = match_upstream_to_parent(e['upstream_60'], catalog)
        if best is None or rate > mismatch_threshold:
            # Unknown bucket key: category 'Unknown', index -1, parent_sequence empty
            key = ('Unknown', -1)
            if key not in aggregates:
                aggregates[key] = {
                    'category': 'Unknown',
                    'parent_index': -1,
                    'parent_sequence': '',
                    'parent_len': 0,
                    'match_len': 0,
                    'mismatch_rate': 1.0,
                    'tp_count': 0,
                    'fn_count': 0,
                    'tp_mutated': 0,
                    'fn_mutated': 0,
                }
            agg = aggregates[key]
            # Update counts
            if e['classification'] == 'TP':
                agg['tp_count'] += 1
                agg['tp_mutated'] += 1  # treat as mutated
            else:
                agg['fn_count'] += 1
                agg['fn_mutated'] += 1
            continue

        key = (best['category'], best['parent_index'])
        if key not in aggregates:
            aggregates[key] = {
                'category': best['category'],
                'parent_index': best['parent_index'],
                'parent_sequence': best['parent_sequence'],
                'parent_len': best['parent_len'],
                'match_len': match_len,
                'mismatch_rate': rate,
                'tp_count': 0,
                'fn_count': 0,
                'tp_mutated': 0,
                'fn_mutated': 0,
            }
        agg = aggregates[key]
        # Update match fields to reflect the best (lowest) mismatch_rate and longest match_len if improved
        if rate < agg['mismatch_rate'] or (rate == agg['mismatch_rate'] and match_len > agg['match_len']):
            agg['mismatch_rate'] = rate
            agg['match_len'] = match_len

        if e['classification'] == 'TP':
            agg['tp_count'] += 1
            if rate > 0:
                agg['tp_mutated'] += 1
        else:
            agg['fn_count'] += 1
            if rate > 0:
                agg['fn_mutated'] += 1

    # Convert to sorted list: by category, then descending tp_count+fn_count
    rows = list(aggregates.values())
    rows.sort(key=lambda r: (r['category'], -(r['tp_count'] + r['fn_count'])))
    return rows


def write_tsv(output_path: Path, rows: List[Dict]):
    header = [
        'category', 'parent_index', 'parent_sequence', 'parent_len',
        'match_len', 'mismatch_rate', 'tp_count', 'fn_count', 'tp_mutated', 'fn_mutated'
    ]
    with open(output_path, 'w') as f:
        f.write('\t'.join(header) + '\n')
        for r in rows:
            f.write('\t'.join([
                str(r['category']),
                str(r['parent_index']),
                str(r['parent_sequence']),
                str(r['parent_len']),
                str(r['match_len']),
                f"{r['mismatch_rate']:.3f}",
                str(r['tp_count']),
                str(r['fn_count']),
                str(r['tp_mutated']),
                str(r['fn_mutated']),
            ]) + '\n')


def main():
    parser = argparse.ArgumentParser(description='Break down TP/FN by UTR category and parent sequence')
    parser.add_argument('--report-file', type=str, required=True, help='Path to prediction report .txt')
    parser.add_argument('--mismatch-threshold', type=float, default=0.15, help='Max mismatch rate for parent assignment (0..1)')
    args = parser.parse_args()

    report_path = Path(args.report_file)
    if not report_path.exists():
        print(f"Report file not found: {report_path}")
        sys.exit(1)

    entries = parse_report_for_tp_fn(report_path)
    rows = analyze_distribution(entries, args.mismatch_threshold)

    # Write TSV next to the report, with _breakdown suffix
    output_path = report_path.with_name(report_path.stem + '_breakdown.tsv')
    write_tsv(output_path, rows)
    print(f"✓ Breakdown written to: {output_path}")


if __name__ == '__main__':
    main()


